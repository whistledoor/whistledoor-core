"""Test vectors for src/fingerprint.ts (crypto-design.md section 4, fingerprints).

Run: python3 -I packages/crypto/vectors/fingerprint.py
Writes vectors/fingerprint.generated.ts next to this file.
"""
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def fingerprint(pk: bytes) -> tuple[bytes, bytes]:
    """Returns the raw 13-byte hash and the fingerprint."""
    digest = hashlib.blake2b(pk, digest_size=13).digest()
    return digest, digest[:12] + bytes([digest[12] & 0xF0])


def encode(fp: bytes) -> str:
    bits = "".join(f"{b:08b}" for b in fp)[:100]
    s = "".join(CROCKFORD[int(bits[i:i + 5], 2)] for i in range(0, 100, 5))
    return "-".join(s[i:i + 4] for i in range(0, 20, 4))


public_keys = {
    "allZero": bytes(32),
    "allOne": bytes([0xFF] * 32),
    "counting": bytes(range(1, 33)),
    # tenant.publicKey from vectors/keys.py.
    "tenant": bytes.fromhex("768a418dd6fffb61e9fb9f8e4ed56f6d903ae4febcc9eeaec45653bc31aff376"),
}

digests = {name: fingerprint(pk)[0] for name, pk in public_keys.items()}
# At least one vector must really lose bits, or the clearing would go untested.
assert any(digest[12] & 0x0F for digest in digests.values())

lines = [
    "// Generated by vectors/fingerprint.py with hashlib.blake2b (no libsodium).",
    "// Do not edit by hand.",
    "",
    "export const FINGERPRINT_VECTORS = [",
]
for name, pk in public_keys.items():
    digest, fp = fingerprint(pk)
    lines += [
        "  {",
        f"    name: '{name}',",
        f"    publicKey: '{pk.hex()}',",
        f"    hash: '{digest.hex()}',",
        f"    bytes: '{fp.hex()}',",
        f"    formatted: '{encode(fp)}',",
        "  },",
    ]
lines += ["] as const;", ""]
with open(os.path.join(HERE, "fingerprint.generated.ts"), "w") as f:
    f.write("\n".join(lines))
for name, pk in public_keys.items():
    print(name, encode(fingerprint(pk)[1]))
