"""Test vectors for src/report.ts and src/files.ts (crypto-design.md sections 5 and 6).

Run: python3 -I packages/crypto/vectors/report.py
Writes vectors/report.generated.ts next to this file.
"""
import base64
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from reference import SecretstreamPush, box_seal, padme, secretbox  # noqa: E402

VERSION = b"\x01"
CHUNK = 64 * 1024
TAG_MESSAGE, TAG_FINAL = 0, 3


def fixed(label: str, size: int) -> bytes:
    return hashlib.blake2b(label.encode(), digest_size=size).digest()


# From the case-code vector "counting" and the tenant key vector in keys.py.
case_key = bytes.fromhex("d12d37106bd1ba4866ac7d7de3b79e7643f1e63145c3489adbf1c9b5dafaf7ce")
tenant_pk = bytes.fromhex("768a418dd6fffb61e9fb9f8e4ed56f6d903ae4febcc9eeaec45653bc31aff376")

report_plain = '{"seq":0,"role":"reporter","text":"Grüße aus Wien.\\nZeile 2 \U0001f511"}'.encode()
report_nonce = fixed("report nonce", 24)


def encrypt_file(data: bytes, key: bytes, header: bytes) -> bytes:
    padded = data + bytes(padme(len(data)) - len(data))
    stream = SecretstreamPush(key, header)
    chunks = [padded[i:i + CHUNK] for i in range(0, len(padded), CHUNK)] or [b""]
    out = VERSION
    for i, chunk in enumerate(chunks):
        out += stream.push(chunk, TAG_FINAL if i == len(chunks) - 1 else TAG_MESSAGE)
    return out


file_key = fixed("file key", 32)
file_header = fixed("file header", 24)
files = {
    "empty": b"",
    "allBytes": bytes(range(256)),
    # Regenerated in the test: byte i is (i * 7 + 3) % 256.
    "twoChunks": bytes((i * 7 + 3) % 256 for i in range(70000)),
}

lines = [
    "// Generated by vectors/report.py from the pure-Python reference in",
    "// vectors/reference.py (no libsodium). Do not edit by hand.",
    "",
    "export const REPORT_VECTORS = {",
    f"  caseKey: '{case_key.hex()}',",
    f"  envelope: '{(VERSION + box_seal(case_key, tenant_pk, fixed('envelope ephemeral', 32))).hex()}',",
    f"  reportPlaintext: '{report_plain.hex()}',",
    f"  reportNonce: '{report_nonce.hex()}',",
    f"  report: '{(VERSION + report_nonce + secretbox(report_plain, report_nonce, case_key)).hex()}',",
    "} as const;",
    "",
    "export const FILE_VECTORS = {",
    f"  fileKey: '{file_key.hex()}',",
    f"  header: '{file_header.hex()}',",
]
for name, data in files.items():
    ct = encrypt_file(data, file_key, file_header)
    lines.append(f"  {name}: {{ size: {len(data)}, ciphertextBase64: '{base64.b64encode(ct).decode()}' }},")
lines += ["} as const;", ""]
with open(os.path.join(HERE, "report.generated.ts"), "w") as f:
    f.write("\n".join(lines))
for name, data in files.items():
    print(name, len(data), "->", padme(len(data)))
