"""Test vectors for src/recovery.ts (crypto-design.md section 4, recovery key).

Run: python3 -I packages/crypto/vectors/recovery.py
Writes vectors/recovery.generated.ts next to this file.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from reference import box_seal, x25519_base  # noqa: E402

VERSION = b"\x01"
CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def fixed(label: str, size: int) -> bytes:
    return hashlib.blake2b(label.encode(), digest_size=size).digest()


def encode(key: bytes) -> str:
    n = int.from_bytes(key, "big")  # 160 bits -> 32 characters, no padding
    s = "".join(CROCKFORD[(n >> (5 * (31 - i))) & 31] for i in range(32))
    return "-".join(s[i:i + 4] for i in range(0, 32, 4))


def kdf(master: bytes, sid: int, ctx: str) -> bytes:
    return hashlib.blake2b(b"", digest_size=32, key=master,
                           salt=sid.to_bytes(8, "little") + bytes(8), person=ctx.encode() + bytes(8)).digest()


def public_key(recovery_key: bytes) -> bytes:
    seed = kdf(hashlib.blake2b(recovery_key, digest_size=32).digest(), 1, "WDrcvr01")
    sk = hashlib.sha512(seed).digest()[:32]  # crypto_box_seed_keypair
    return x25519_base(sk)


# Same tenant key pair as vectors/keys.py. Only the public key goes into the
# generated file: tests check the recovered tenant key through it.
tenant_sk = fixed("tenant sk", 32)

keys = {
    "allZero": bytes(20),
    "allOne": bytes([0xFF] * 20),
    "counting": bytes(range(1, 21)),
}
lines = [
    "// Generated by vectors/recovery.py from the pure-Python reference in",
    "// vectors/reference.py (no libsodium). Do not edit by hand.",
    "",
    "export const RECOVERY_VECTORS = [",
]
for name, key in keys.items():
    pk = public_key(key)
    grant = VERSION + box_seal(tenant_sk, pk, fixed(f"recovery grant {name}", 32))
    lines += [
        "  {",
        f"    name: '{name}',",
        f"    bytes: '{key.hex()}',",
        f"    formatted: '{encode(key)}',",
        f"    publicKey: '{pk.hex()}',",
        f"    grant: '{grant.hex()}',",
        "  },",
    ]
lines += ["] as const;", "", f"export const RECOVERY_TENANT_PUBLIC_KEY = '{x25519_base(tenant_sk).hex()}';", ""]
with open(os.path.join(HERE, "recovery.generated.ts"), "w") as f:
    f.write("\n".join(lines))
for name, key in keys.items():
    print(name, encode(key))
