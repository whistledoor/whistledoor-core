"""Test vectors for src/notes.ts (crypto-design.md section 5, internal notes).

Run: python3 -I packages/crypto/vectors/notes.py
Writes vectors/notes.generated.ts next to this file.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from reference import box_seal, secretbox  # noqa: E402

VERSION = b"\x01"


def fixed(label: str, size: int) -> bytes:
    return hashlib.blake2b(label.encode(), digest_size=size).digest()


# Tenant public key from vectors/keys.py.
tenant_pk = bytes.fromhex("768a418dd6fffb61e9fb9f8e4ed56f6d903ae4febcc9eeaec45653bc31aff376")

notes_key = fixed("notes key", 32)
note_nonce = fixed("note nonce", 24)
note_plain = '{"text":"Rückruf am Montag, nicht an die Meldeperson weitergeben. \U0001f4dd"}'.encode()

notes_envelope = VERSION + box_seal(notes_key, tenant_pk, fixed("notes envelope ephemeral", 32))
note = VERSION + note_nonce + secretbox(note_plain, note_nonce, notes_key)

lines = [
    "// Generated by vectors/notes.py from the pure-Python reference in",
    "// vectors/reference.py (no libsodium). Do not edit by hand.",
    "",
    "export const NOTES_VECTORS = {",
    f"  notesKey: '{notes_key.hex()}',",
    f"  notesEnvelope: '{notes_envelope.hex()}',",
    f"  notePlaintext: '{note_plain.hex()}',",
    f"  noteNonce: '{note_nonce.hex()}',",
    f"  note: '{note.hex()}',",
    "} as const;",
    "",
]
with open(os.path.join(HERE, "notes.generated.ts"), "w") as f:
    f.write("\n".join(lines))
print("notesEnvelope", len(notes_envelope), "bytes, note", len(note), "bytes")
